const slug = (cat, i, title) => `seed-${cat}-${String(i + 1).padStart(2, '0')}`;
const esc = (s) => s.replace(/"/g, '\\"');

let written = 0;
let imgIndex = 0;
let dayOffset = 0;

for (const [cat, titles] of Object.entries(LIST)) {
  const bodyTpl = BODY[cat];
  titles.forEach((title, i) => {
    const place = PLACES[(i + cat.length) % PLACES.length];
    const paras = bodyTpl.map((fn) => fn(title, place));
    const date = new Date(Date.UTC(2026, 10, 19 - dayOffset));
    dayOffset = (dayOffset + 0.34) % 26;

    const fm = [
      '---',
      `title: "${esc(title)}"`,
      `dek: "${esc(paras[0].slice(0, 110))}…"`,
      `category: ${cat}`,
      `date: ${date.toISOString().slice(0, 10)}`,
      `author: "${AUTHORS[cat]}"`,
      `image: /images/${IMAGES[imgIndex % IMAGES.length]}`,
      `imageAlt: "${esc(title)}"`,
      'featured: false',
      `tags: [${TAGS[cat].map((t) => `"${t}"`).join(', ')}]`,
      '---',
      '',
    ].join('\n');

    writeFileSync(join(OUT, `${slug(cat, i, title)}.md`), fm + paras.join('\n\n') + '\n', 'utf8');
    written += 1;
    imgIndex += 1;
  });
}

console.log(`wrote ${written} posts`);
